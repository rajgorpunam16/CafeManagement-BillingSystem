    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
   String itemName = jTextField1.getText().trim();
    String priceText = jTextField2.getText().trim();
    String category = (String) jComboBox1.getSelectedItem();

    // ✅ VALIDATION
    if (itemName.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "⚠ Please enter item name");
        return;
    }
if (imagePath.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this, "⚠ Please upload image");
    return;
}
    if (priceText.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "⚠ Please enter price");
        return;
    }

    double price = 0;
    try {
        price = Double.parseDouble(priceText);
        if (price <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "⚠ Price must be greater than 0");
            return;
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "⚠ Enter valid numeric price");
        return;
    }

    if (category == null || category.contains("Choose")) {
        javax.swing.JOptionPane.showMessageDialog(this, "⚠ Please select category");
        return;
    }

    if (imagePath.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "⚠ Please upload image");
        return;
    }

    // ✅ DATABASE INSERT
    try (Connection con = DBConnection.getConnection()) {

        String sql = "INSERT INTO menu_items (item_name, price, category, image_path) VALUES (?, ?, ?, ?)";
        java.sql.PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, itemName);
        pst.setDouble(2, price);
        pst.setString(3, category);
        pst.setString(4, imagePath); // ✅ SAVE IMAGE PATH

        int rows = pst.executeUpdate();

        if (rows > 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "✅ Item added successfully!");

            // ✅ CLEAR FORM
            jTextField1.setText("");
            jTextField2.setText("");
            jComboBox1.setSelectedIndex(0);
            jLabel6.setIcon(null);
            jLabel6.setText("No Image Selected");
            imagePath = "";
        }

    } catch (Exception e) {
        e.printStackTrace();
        javax.swing.JOptionPane.showMessageDialog(this, "❌ Error adding item");
    }
    // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

