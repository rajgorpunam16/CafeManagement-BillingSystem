    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed

    javax.swing.JFileChooser chooser = new javax.swing.JFileChooser();
    int result = chooser.showOpenDialog(this);

    if (result == javax.swing.JFileChooser.APPROVE_OPTION) {
        java.io.File file = chooser.getSelectedFile();

        try {
            // Create images folder if not exists
            java.io.File dir = new java.io.File("images");
            if (!dir.exists()) {
                dir.mkdir();
            }

            // Save relative path
            imagePath = "images/" + file.getName();

            // Copy file
            java.nio.file.Files.copy(
                file.toPath(),
                new java.io.File(imagePath).toPath(),
                java.nio.file.StandardCopyOption.REPLACE_EXISTING
            );

            // Show preview
            javax.swing.ImageIcon icon = new javax.swing.ImageIcon(file.getAbsolutePath());
            java.awt.Image img = icon.getImage().getScaledInstance(300, 250, java.awt.Image.SCALE_SMOOTH);

            jLabel6.setIcon(new javax.swing.ImageIcon(img));
            jLabel6.setText("");

        } catch (Exception e) {
            e.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(this, "Error loading image");
        }
    }// TODO add your handling code here:
    }//GEN-LAST:event_jButton4ActionPerformed

