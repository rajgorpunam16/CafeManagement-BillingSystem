    private void jButtonDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDeleteActionPerformed
       int selectedRow = jTableWaiters.getSelectedRow();
    if (selectedRow >= 0) {
        int id = (int) jTableWaiters.getValueAt(selectedRow, 0); // get waiter ID

        int confirm = JOptionPane.showConfirmDialog(this,
                "Are you sure you want to delete this waiter?",
                "Confirm Delete", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                Connection con = DBConnection.getConnection();
                String sql = "DELETE FROM waiter WHERE id=?";
                PreparedStatement pst = con.prepareStatement(sql);
                pst.setInt(1, id);
                pst.executeUpdate();

                JOptionPane.showMessageDialog(this, "Waiter deleted successfully!");
                loadTable(); // refresh table after deletion

            } catch (Exception e) {
                e.printStackTrace();
            }
        }

    } else {
        JOptionPane.showMessageDialog(this, "Please select a waiter to delete.");
    } // TODO add your handling code here:
    }//GEN-LAST:event_jButtonDeleteActionPerformed

