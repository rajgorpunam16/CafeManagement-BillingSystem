private void loadTable() {
 
    try {
        Connection con = DBConnection.getConnection();
        String sql = "SELECT id, name, phone, dob, username, password, age, address, gender FROM waiter";
        PreparedStatement pst = con.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        String[] columns = {
            "Waiter ID", "Full Name", "Phone Number", "Date of Birth",
            "Username", "Password", "Age", "Address", "Gender"
        };

        DefaultTableModel model = new DefaultTableModel(columns, 0);
        jTableWaiters.setModel(model);

        while (rs.next()) {
            Object[] row = {
                rs.getInt("id"),          // ✅ FIXED
                rs.getString("name"),    // ✅ FIXED
                rs.getString("phone"),   // ✅ FIXED
                rs.getString("dob"),     // ✅ FIXED
                rs.getString("username"),
                rs.getString("password"),
                rs.getInt("age"),
                rs.getString("address"),
                rs.getString("gender")
            };
            model.addRow(row);
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error loading data: " + e.getMessage());
    }
}
